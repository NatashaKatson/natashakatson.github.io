#!/usr/bin/env python3
"""Build all Natural Earth country search destinations from the detailed map.

Uses only Python's standard library. A scan line inside the largest land component
keeps navigation on land rather than at a multipolygon centroid in the ocean.
Browser regression checks verify containment against the actual D3 renderer.
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'static/historyallaround/atlas'


def countries(topology):
    scale = topology['transform']['scale']
    translate = topology['transform']['translate']
    arcs = []
    for source in topology['arcs']:
        x = y = 0
        arc = []
        for dx, dy in source:
            x += dx
            y += dy
            arc.append([x * scale[0] + translate[0], y * scale[1] + translate[1]])
        arcs.append(arc)

    def ring(indices):
        points = []
        for index in indices:
            arc = arcs[index if index >= 0 else ~index]
            segment = arc if index >= 0 else list(reversed(arc))
            points.extend(segment if not points else segment[1:])
        # Keep antimeridian components contiguous in the local planar calculation.
        unwrapped = [points[0]]
        for x, y in points[1:]:
            previous = unwrapped[-1][0]
            while x - previous > 180:
                x -= 360
            while x - previous < -180:
                x += 360
            unwrapped.append([x, y])
        return unwrapped

    def area(polygon):
        exterior = polygon[0]
        value = abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(exterior, exterior[1:])))
        return value * math.cos(math.radians(sum(p[1] for p in exterior) / len(exterior)))

    def interior(polygon):
        # Put holes in the same longitude frame as the exterior.
        longitude = sum(p[0] for p in polygon[0]) / len(polygon[0])
        aligned = [polygon[0]]
        for hole in polygon[1:]:
            shift = round((longitude - sum(p[0] for p in hole) / len(hole)) / 360) * 360
            aligned.append([[x + shift, y] for x, y in hole])
        south = min(p[1] for p in polygon[0])
        north = max(p[1] for p in polygon[0])
        best = None
        for fraction in [.5, .4, .6, .3, .7, .2, .8, .1, .9]:
            y = south + (north - south) * fraction
            xs = sorted(a[0] + (y - a[1]) * (b[0] - a[0]) / (b[1] - a[1])
                        for boundary in aligned for a, b in zip(boundary, boundary[1:])
                        if (a[1] > y) != (b[1] > y))
            for left, right in zip(xs[::2], xs[1::2]):
                width = (right - left) * math.cos(math.radians(y))
                if best is None or width > best[0]:
                    best = (width, (left + right) / 2, y)
        if best is None:
            raise ValueError('Could not find an interior country point')
        return [((best[1] + 180) % 360) - 180, best[2]]

    rows = []
    for geometry in topology['objects']['countries']['geometries']:
        source = [geometry['arcs']] if geometry['type'] == 'Polygon' else geometry['arcs']
        polygons = [[ring(boundary) for boundary in polygon] for polygon in source]
        point = interior(max(polygons, key=area))
        rows.append([geometry['properties']['name'], *point])
    return sorted(rows)


def build(check=False):
    data = {'version': 1, 'source': 'Natural Earth 1:50m', 'rows': countries(json.loads((ROOT / 'land-50m.json').read_text()))}
    output = '/* Generated by scripts/build-history-countries.py; Natural Earth public-domain geography. */\n'
    output += '(function(root){const data=' + json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    output += ";if(typeof module==='object')module.exports=data;else root.HistoryCountries=data;})(globalThis);\n"
    destination = ROOT / 'search-countries.js'
    if check:
        if not destination.exists() or destination.read_text() != output:
            raise SystemExit('Country search data is stale; run python3 scripts/build-history-countries.py')
    else:
        destination.write_text(output)
    print(f'{len(data["rows"])} country and territory destinations; {"verified" if check else "generated"}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
