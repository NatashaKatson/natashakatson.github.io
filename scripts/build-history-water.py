#!/usr/bin/env python3
"""Bundle Natural Earth inland water for the atlas; no runtime download.

Usage: python3 -B scripts/build-history-water.py /path/to/ne_50m_lakes.geojson
Source: Natural Earth 1:50m lakes, public domain.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'static/historyallaround/atlas'


def polygon(rings):
    result = []
    for i, raw in enumerate(rings):
        ring = [[round(x, 5), round(y, 5)] for x, y in raw]
        area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(ring, ring[1:]))
        result.append(list(reversed(ring)) if (area > 0) == (i == 0) else ring)
    return result


def build(source):
    features = []
    for f in json.loads(Path(source).read_text())['features']:
        p, g = f['properties'], f['geometry']
        name = p.get('name') or p.get('name_en') or 'Unnamed lake'
        group = 'Aral Sea' if p.get('name') in {'North Aral Sea', 'South Aral Sea'} else name
        geometry = {**g, 'coordinates': polygon(g['coordinates']) if g['type'] == 'Polygon'
                    else [polygon(rings) for rings in g['coordinates']]}
        reservoir = p.get('featurecla') == 'Reservoir' or 'reservoir' in name.lower()
        features.append({'type': 'Feature', 'properties': {'name': group, 'reservoir': reservoir}, 'geometry': geometry})
    data = {'type': 'FeatureCollection', 'source': 'Natural Earth 1:50m, public domain',
            'url': 'https://www.naturalearthdata.com/downloads/50m-physical-vectors/50m-lakes/',
            'features': features}
    output = '/* Generated by scripts/build-history-water.py; Natural Earth, public domain. */\n'
    output += '(function(root){const data=' + json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    output += ';if(typeof module==="object")module.exports=data;else root.ATLAS_WATER=data;})(globalThis);\n'
    (ROOT / 'water-data.js').write_text(output)
    print(f'water-data.js: {len(features)} water features; {len(output.encode()):,} bytes')


if __name__ == '__main__':
    build(sys.argv[1])
