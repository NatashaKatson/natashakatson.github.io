#!/usr/bin/env python3
"""Bundle Great Lakes water and the US–Canada boundary independently.

Usage: python3 scripts/build-history-great-lakes.py /path/to/ne_50m_lakes.geojson
Lake source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_lakes.geojson
The boundary comes from the already bundled Natural Earth 1:50m countries.
Natural Earth data is public domain. No runtime network service is used.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'static/historyallaround/atlas'


def ring_points(topo, ring):
    points = []
    for index in ring:
        x = y = 0
        arc = []
        for dx, dy in topo['arcs'][index if index >= 0 else ~index]:
            x += dx
            y += dy
            arc.append([round(v * s + t, 6) for v, s, t in zip(
                (x, y), topo['transform']['scale'], topo['transform']['translate'])])
        if index < 0:
            arc.reverse()
        points.extend(arc[1:] if points else arc)
    return points


def lake_geometry(geometry):
    def polygon(rings):
        result = []
        for i, ring in enumerate(rings):
            area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(ring, ring[1:]))
            # D3 uses clockwise exteriors and counterclockwise holes.
            result.append(list(reversed(ring)) if (area > 0) == (i == 0) else ring)
        return result
    return {**geometry, 'coordinates': polygon(geometry['coordinates'])
            if geometry['type'] == 'Polygon' else [polygon(p) for p in geometry['coordinates']]}


def build(lakes_path):
    topo = json.loads((ROOT / 'land-50m.json').read_text())
    us = next(g for g in topo['objects']['countries']['geometries']
              if g['properties']['name'] == 'United States of America')
    rings = [ring_points(topo, p[0]) for p in us['arcs']]
    mainland = next(r for r in rings if min(p[0] for p in r) < -120 and max(p[0] for p in r) > -70)
    nearest = lambda p: min(range(len(mainland) - 1), key=lambda i:
                            sum((a - b) ** 2 for a, b in zip(mainland[i], p)))
    west, east = nearest([-89.9, 48]), nearest([-75, 45])
    assert west < east
    boundary = mainland[west:east + 1]
    assert all(-93 < x < -74 and 40 < y < 50 for x, y in boundary)
    names = {'Lake Superior', 'Lake Michigan', 'Lake Huron', 'Lake Erie', 'Lake Ontario', 'Lake Saint Clair'}
    lakes = [{'type': 'Feature', 'properties': {'name': f['properties']['name']},
              'geometry': lake_geometry(f['geometry'])}
             for f in json.loads(Path(lakes_path).read_text())['features'] if f['properties']['name'] in names]
    assert {f['properties']['name'] for f in lakes} == names
    data = {'source': 'Natural Earth 1:50m, public domain',
            'lakesSource': 'https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_lakes.geojson',
            'boundarySource': 'land-50m.json', 'from': 1932,
            'boundary': {'type': 'LineString', 'coordinates': boundary},
            'lakes': {'type': 'FeatureCollection', 'features': lakes}}
    output = '/* Generated by scripts/build-history-great-lakes.py; Natural Earth, public domain. */\n'
    output += '(function(root){const data=' + json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    output += ';if(typeof module==="object")module.exports=data;else root.HistoryGreatLakes=data;})(globalThis);\n'
    (ROOT / 'great-lakes.js').write_text(output)
    print(f'great-lakes.js: {len(lakes)} lakes; {len(boundary)} boundary vertices; {len(output):,} bytes')


if __name__ == '__main__':
    build(sys.argv[1])
